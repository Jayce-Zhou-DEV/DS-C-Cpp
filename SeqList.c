/*
 * TODO[4] ★★★ 你现在遇到的“打印出垃圾数”的真正原因 ★★★
 *
 *   void InitList(SeqList list)    // ← 注意：形参前面没有 *
 *
 *   C 的参数是“值传递”：调用 InitList(list) 时，会把 main 里的 list
 *   **整个复制一份** 交给形参。你在函数里写的 list.length = 0，
 *   改的是这份“复印件”。
 *   函数一返回，复印件被丢掉 —— main 里那张 list 从头到尾没被碰过。
 *
 *   于是 main 里：length 还是内存里的随机值，data 也从来没被写过。
 *   PrintList 按这个随机 length 去循环，当然打印出一堆垃圾 —— 这就是你看到的现象。
 *
 *   要让函数真正改到“外面那张表”，必须传地址（指针）：
 *     [ ] 形参改成指针类型，例如  SeqList *L
 *     [ ] 调用处改成传地址，例如  InitList(&list)
 *     [ ] 函数体内改用箭头访问成员：L->length，而不是 list.length
 *
 *   ⚠ 同一个坑也在 ListInsert 上：它现在收到的也是复印件，
 *     所以“插入”的动作全落在一份马上被丢掉的副本里。
 *     （PrintList 只是读，传复印件问题不大，可以不改。）
 */
void InitList(SeqList *list){
    list->length = 0;
}

