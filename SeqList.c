/*
 * TODO[5]: ListInsert 除了“传值”这个大坑，还有 3 个小问题：
 *
 *   ① 形参第一项叫 i，但你函数体里把它当“要存的值”用了（data[...] = i）。
 *      名字和用途不符会把自己绕晕。写插入前先想清楚：
 *      你到底想支持“按位置 i 插入”，还是“只往尾部追加”？先定下来。
 *
 *   ② 判满写的 list.length > 10：length 恰好等于 10 时就是满了，
 *      这时还允许写 data[10] 就越界了。想想该用 > 还是 >= ？
 *      再想：这个 10 是不是该换成容量宏，别到处硬编码？
 *
 *   ③ 现在不管传什么位置，都只往尾部追加，中间插入的“移位”逻辑还没有。
 *      见上方“关键提示 A”：移位时循环变量要从大到小，否则数据会被覆盖。
 */
int ListInsert(int i ,SeqList *list) {
    if (list->length > 10) return 0;
    list->data[list->length] = i;
    list->length ++;
    return 1;
}


